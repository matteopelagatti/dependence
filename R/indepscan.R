#' Scan the order grid of the independence test
#'
#' @description
#' `indepscan()` evaluates the Pillai statistic at every order
#' \eqn{(k,k)}, \eqn{k = 1, \ldots, K}, converts each to its exact null
#' p-value, and reports the smallest of them. It is the adaptive form of
#' [indeptest()]: instead of committing to one order it looks at the whole
#' nested family and lets the data choose, paying for the look through a
#' critical value calibrated on the joint null rather than through Bonferroni.
#'
#' @details
#' **Why this is nearly free with the polynomial basis.** That basis is
#' generated by a recurrence and orthonormalised in order, so it is nested:
#' \eqn{B[, 1:k]} is the order-\eqn{k} basis. With separated ties the scaled
#' ranks are a permutation of the grid, \eqn{S_{uu}} and \eqn{S_{vv}} are
#' identities, no whitening is needed, and the statistics \eqn{P_n(k,k)} are
#' partial sums of the squared entries of one \eqn{K \times K} cross-moment
#' matrix:
#' \deqn{P_n(k,k) = n \sum_{i \le k} \sum_{j \le k} S_{ij}^2 .}
#' One pass at order \eqn{K} then yields the entire profile at the cost of
#' the largest order alone -- about a sixfold saving at \eqn{K = 6} over
#' calling [indeptest()] \eqn{K} times, which would build \eqn{K} bases and
#' rank the data \eqn{2K} times for the same answer.
#'
#' **The spline basis is not nested, and the profile is still correct.**
#' `splines::bs(df = k)` moves its interior knots with `k`, so the leading
#' columns of the order-\eqn{K} spline basis are not the order-\eqn{k} basis
#' -- they are the first few B-splines, supported near the left end of the
#' range. The partial-sum shortcut would therefore give the wrong answer
#' there, and is not used: each order gets its own build. The same holds
#' under `ties = "average"`, where tied observations share a rank and the
#' whitening depends on the order. Either route agrees with
#' `indeptest(p = k, q = k)` to machine precision, which `tests/` asserts.
#' Note that `"average"` forfeits exact distribution-freeness, which the
#' calibration here relies on; ties of any kind make the tabulated null
#' approximate and raise a warning.
#'
#' **Weights.** The rule is: reject when \eqn{p_k < c\,w_k} for some \eqn{k},
#' with \eqn{c} fixed so the size is exactly \eqn{\alpha}. Uniform weights
#' make no assumption about where the dependence lies. Decreasing weights,
#' for instance \eqn{w_k \propto 2^{-k}}, spend most of the level at
#' \eqn{k = 1}, where the statistic is a monotone function of Spearman's
#' correlation, and so favour monotone dependence at the expense of
#' higher-order structure.
#'
#' **The null table is doing real work.** The \eqn{K} statistics are nested
#' partial sums of one array and are strongly positively correlated -- null
#' correlations between adjacent orders run from about 0.4 to 0.8 -- so a
#' Bonferroni threshold is badly conservative. Calibrating on the simulated
#' joint null recovers that margin as power. The simulation is exact rather
#' than asymptotic because, with separated ties and continuous margins, the
#' whole scan is a function of the two rank vectors alone.
#'
#' @param x,y Numeric vectors of the same length.
#' @param null An object from [indepscan_null()], tabulated at the same `n`,
#'   `K` and `basis`.
#' @param weights Either `"uniform"` (the default) or a positive numeric
#'   vector of length `K`, which is normalised internally. Weights may be
#'   changed freely without retabulating the null.
#' @param basis,ties Passed through as in [indeptest()]; must match the
#'   settings used for `null`.
#'
#' @return An object of class `"indepscan"`, a list with
#'   \item{`statistic`}{the scan statistic \eqn{\min_k p_k / w_k}.}
#'   \item{`p.value`}{its exact p-value, read from the tabulated null.}
#'   \item{`profile`}{the vector of \eqn{P_n(k,k)}, \eqn{k = 1, \ldots, K}.}
#'   \item{`cell.pvalues`}{the per-order null p-values \eqn{p_k}.}
#'   \item{`k.min`}{the order attaining the minimum, a description of where
#'     the evidence sits, not a selected model.}
#'
#' @seealso [indeptest()] for the fixed-order test, [indepscan_null()] for
#'   the tabulation.
#'
#' @examples
#' \donttest{
#' set.seed(1)
#' tab <- indepscan_null(n = 100, K = 5, R = 2000)   # R = 2e4 in earnest
#' x <- runif(100); y <- sin(4 * pi * x) + 0.4 * rnorm(100)
#' indepscan(x, y, tab)
#' indeptest(x, y)          # the fixed-order test, for comparison
#' }
#' @export
indepscan <- function(x, y, null,
                      weights = "uniform",
                      basis = c("poly", "spline"),
                      ties  = c("first", "last", "random", "average")) {
  basis <- match.arg(basis)
  ties  <- match.arg(ties)
  n <- length(x)
  if (length(y) != n)
    stop("x and y must have the same length.")
  if (missing(null) || !inherits(null, "indepscan_null"))
    stop("'null' must be an object from indepscan_null().")
  if (null$n != n)
    stop(sprintf("null table is for n = %d but the data have n = %d.",
                 null$n, n))
  if (null$basis != basis)
    stop(sprintf("null table uses basis '%s' but '%s' was requested.",
                 null$basis, basis))
  K <- null$K
  scan_check_K(K, n, x, y)
  w <- scan_weights(weights, K)
  ## The table is drawn from continuous uniforms, so it is the exact null
  ## only for untied data.  With ties the statistic is still a function of
  ## the ranks, but of ranks with a different law, and the p-value becomes
  ## an approximation whose direction is not guaranteed.
  if (anyDuplicated(x) > 0L || anyDuplicated(y) > 0L)
    warning("the data contain ties, so the tabulated null is approximate; ",
            "a permutation p-value is exact in that case.", call. = FALSE)

  prof <- scan_profile(x, y, K, basis, ties)
  pk <- vapply(seq_len(K), function(k)
    1 - findInterval(prof[k], null$cells[[k]]) / length(null$cells[[k]]), 0)
  stat <- min(pk / w)
  nullstat <- scan_nullstat(null, w)
  pval <- (1 + findInterval(stat, nullstat)) / (1 + length(nullstat))

  structure(
    list(statistic = stat,
         p.value   = pval,
         profile   = prof,
         cell.pvalues = pk,
         k.min     = which.min(pk / w),
         weights   = w,
         K = K, basis = basis, ties = ties, nobs = n,
         method = "Pelagatti-Monti independence test, order scan"),
    class = "indepscan")
}


#' Tabulate the null distribution for the order scan
#'
#' @description
#' Simulates the joint null of the nested family \eqn{P_n(k,k)},
#' \eqn{k = 1, \ldots, K}, under independence. Because the statistics depend
#' on the data only through the two rank vectors, the law does not depend on
#' the marginals and the table is exact for every pair of continuous
#' variables of that length.
#'
#' @details
#' Two independent batches are drawn, and this is not a refinement: the first
#' fixes the null law of each order, the second is pushed through those laws
#' to calibrate the scan. Using one batch for both would evaluate the scan on
#' the very draws that defined its own reference distribution, and the test
#' would reject too often.
#'
#' The second batch is stored as a matrix of null p-values rather than as a
#' single critical value, so that any weight profile can be applied afterwards
#' without retabulating. For `K = 6` and `R = 2e4` that is about 1 Mb.
#'
#' Tabulation costs \eqn{2R} evaluations of an order-\eqn{K} cross-moment
#' matrix, a few seconds to a few minutes depending on `n` and `R`. It is done
#' once per `(n, K, basis)` and is worth caching with [saveRDS()].
#'
#' @param n Sample size the table will be used for.
#' @param K Largest order in the scan. It should grow with `n`: the scan
#'   inherits consistency only through the spans it looks at, so a fixed `K`
#'   bounds the alternatives it is consistent against. The default follows
#'   the growth rule of [indeptest()], two orders above it.
#' @param R Replications per batch.
#' @param basis,ties As in [indeptest()].
#' @param seed Optional integer, for reproducible tables.
#'
#' @return An object of class `"indepscan_null"`.
#' @export
indepscan_null <- function(n, K = as.integer(floor(n^0.31)) + 1L,
                           R = 2e4,
                           basis = c("poly", "spline"),
                           ties  = c("first", "last", "random"),
                           seed = NULL) {
  basis <- match.arg(basis)
  ties  <- match.arg(ties)
  n <- as.integer(n); K <- as.integer(K); R <- as.integer(R)
  scan_check_K(K, n)
  if (!is.null(seed)) set.seed(seed)

  ## The basis depends on n and K alone, so it is built once and reused
  ## across all 2R draws instead of 2R times.
  bases <- scan_basis(n, K, basis)
  draw <- function() {
    M <- matrix(NA_real_, R, K)
    for (i in seq_len(R))
      M[i, ] <- scan_profile(stats::runif(n), stats::runif(n), K, basis,
                             ties, bases)
    M
  }
  A <- draw()                                   # fixes the per-order laws
  cells <- lapply(seq_len(K), function(k) sort(A[, k]))
  B <- draw()                                   # calibrates the scan
  pmat <- vapply(seq_len(K), function(k)
    1 - findInterval(B[, k], cells[[k]]) / R, numeric(R))

  ## An environment, so the memo in scan_nullstat() survives being passed
  ## by value to indepscan().
  out <- structure(list(n = n, K = K, R = R, basis = basis, ties = ties,
                        cells = cells, pmat = pmat,
                        cache = new.env(parent = emptyenv())),
                   class = "indepscan_null")
  invisible(scan_nullstat(out, scan_weights("uniform", K)))   # warm the default
  out
}


#' Order range admissible for a scan
#'
#' @description
#' The profile and the null table are indexed by the same \eqn{K}, so an
#' order the data cannot support must raise an error rather than be capped
#' silently: a shortened profile would be read against the wrong column of
#' the table. This is why `scan_profile()` does not call `cap_order()`,
#' which caps with a warning and would emit one on each of the \eqn{2R}
#' tabulation draws.
#'
#' @keywords internal
#' @noRd
scan_check_K <- function(K, n, x = NULL, y = NULL) {
  if (length(K) != 1L || is.na(K) || K < 1L)
    stop("K must be a single integer of at least 1.")
  if (K >= n)
    stop(sprintf("K = %d is not usable at n = %d; K must be well below n.",
                 K, n))
  for (v in list(x = x, y = y)) {
    if (is.null(v)) next
    d <- length(unique(v))
    if (K > d - 1L)
      stop(sprintf(paste("K = %d exceeds what the data support: one variable",
                         "has %d distinct values, allowing order %d at most.",
                         "Re-tabulate the null at the smaller K."),
                   K, d, d - 1L))
  }
  invisible(TRUE)
}


#' Basis matrices for orders 1 to K
#'
#' @description
#' Returns a list whose \eqn{k}-th element is the basis [indeptest()] would
#' use at \eqn{p = q = k}. It depends on `n` and `K` alone, never on the
#' data, so one list serves all \eqn{2R} tabulation draws.
#'
#' @details
#' The polynomial basis is **nested**: it is generated by a recurrence and
#' orthonormalised in order, so the order-\eqn{k} basis is the leading
#' \eqn{k} columns of the order-\eqn{K} one. The spline basis is **not**:
#' `splines::bs(df = k)` moves its interior knots with `k`, so the leading
#' columns of the order-\eqn{K} basis span something else entirely -- and
#' being the first few B-splines, they are supported near the left end of
#' the range rather than over all of it. Each order therefore gets its own
#' build. (`bs` also silently raises `df` to 3, so the first three entries
#' of the list are leading sub-blocks of the same matrix; that is the
#' convention [indeptest()] already follows at those orders.)
#'
#' @keywords internal
#' @noRd
scan_basis <- function(n, K, basis = "poly") {
  ## The polynomial basis is nested, so the n x K matrix itself serves every
  ## order: order k is its first k columns.  Storing the K leading blocks as
  ## separate copies, as an earlier version did, costs n K (K + 1) / 2
  ## doubles, 21.6 GB at n = 1e6 and K = 73, and made the profile five
  ## times slower than one evaluation of B_n at that size.
  if (basis == "poly") return(chebyshev_basis(n, K))

  lapply(seq_len(K), function(k) {
    Bk <- suppressWarnings(ortho_spline_basis_int(n, k))
    if (ncol(Bk) < k)
      stop(sprintf("spline basis of order %d unavailable at n = %d.", k, n))
    Bk[, seq_len(k), drop = FALSE]
  })
}


#' Profile of Pillai statistics over orders 1 to K
#'
#' @description
#' Returns \eqn{P_n(k,k)} for \eqn{k = 1, \ldots, K}. Equal, order by order,
#' to `indeptest(x, y, p = k, q = k)$P_stat`, and verified against it.
#'
#' @details
#' With the polynomial basis and separated ties the whole profile comes from
#' one pass: the ranks are then a permutation of the grid, so the Gram
#' matrices are the identity, the bare cross-product is already whitened at
#' every order, and \eqn{P_n(k,k)} is the partial sum of its squared entries
#' over the leading \eqn{k \times k} block. Shared ranks make the whitening
#' order-dependent, and the spline basis is not nested, so either one sends
#' the computation down the per-order route.
#'
#' @param bases Optional output of `scan_basis()`, to be reused across draws:
#'   the n x K matrix for the polynomial basis (a list of the K leading
#'   blocks is also accepted), a list of per-order matrices for splines.
#'
#' @keywords internal
#' @noRd
scan_profile <- function(x, y, K, basis = "poly", ties = "first",
                         bases = NULL) {
  n <- length(x)
  if (is.null(bases)) bases <- scan_basis(n, K, basis)
  rx <- rank(x, ties.method = ties)
  ry <- rank(y, ties.method = ties)
  tied <- anyDuplicated(rx) > 0L || anyDuplicated(ry) > 0L
  ix <- as.integer(rx); iy <- as.integer(ry)

  ## order-k block of the basis, from either form of `bases`
  block <- function(k) {
    if (!is.matrix(bases)) return(bases[[k]])
    if (k == ncol(bases)) bases else bases[, seq_len(k), drop = FALSE]
  }

  if (!tied && basis == "poly") {
    B <- block(K)
    S2 <- (crossprod(B[ix, , drop = FALSE], B[iy, , drop = FALSE]) / n)^2
    return(vapply(seq_len(K),
                  function(k) n * sum(S2[seq_len(k), seq_len(k)]), 0))
  }
  vapply(seq_len(K), function(k) {
    Bk <- block(k)
    S <- whiten_cross(Bk[ix, , drop = FALSE], Bk[iy, , drop = FALSE], tied)
    n * sum(S * S)
  }, 0)
}


#' Sorted null distribution of the scan statistic, memoised by weights
#'
#' @description
#' Collapsing the \eqn{R \times K} matrix of null cell p-values to the scan
#' statistic costs \eqn{O(RK)}, which is nothing for one test and everything
#' in a simulation that reuses the same table thousands of times. The result
#' is therefore kept in an environment carried by the table, keyed on the
#' weights, and the p-value is then read off the sorted vector in
#' \eqn{O(\log R)}.
#'
#' @keywords internal
#' @noRd
scan_nullstat <- function(null, w) {
  key <- paste(formatC(w, digits = 12L, format = "g"), collapse = "|")
  cache <- null$cache
  if (is.environment(cache) && !is.null(cache[[key]])) return(cache[[key]])
  v <- sort(do.call(pmin, as.data.frame(sweep(null$pmat, 2L, w, "/"))))
  if (is.environment(cache)) assign(key, v, envir = cache)
  v
}


#' Normalised scan weights
#' @keywords internal
#' @noRd
scan_weights <- function(weights, K) {
  if (identical(weights, "uniform")) return(rep(1/K, K))
  if (identical(weights, "geometric")) {
    w <- 2^-seq_len(K); return(w / sum(w))
  }
  if (!is.numeric(weights) || length(weights) != K || any(weights <= 0))
    stop("'weights' must be \"uniform\", \"geometric\", or K positive numbers.")
  weights / sum(weights)
}


#' @export
print.indepscan <- function(x, ...) {
  cat("\n", x$method, "\n\n", sep = "")
  cat(sprintf("n = %d,  K = %d,  basis = %s,  ties = %s\n",
              x$nobs, x$K, x$basis, x$ties))
  cat(sprintf("scan statistic = %.5g,  p-value = %.4g\n",
              x$statistic, x$p.value))
  cat(sprintf("smallest at order k = %d\n\n", x$k.min))
  prof <- data.frame(k = seq_len(x$K),
                     P_stat = round(x$profile, 3),
                     p_value = signif(x$cell.pvalues, 3),
                     weight = round(x$weights, 4))
  print(prof, row.names = FALSE)
  cat("\nThe p-value is exact up to the Monte Carlo error of the null table.\n")
  invisible(x)
}
